import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { defineConfig, type Plugin } from 'vite';

const webDir = fileURLToPath(new URL('.', import.meta.url));
const repoRoot = resolve(webDir, '..');
const coreDir = resolve(repoRoot, 'core');

/*
 * Which build of the engine to bundle.
 *
 * Stage A is still in progress, so `core/src/index.ts` may not exist yet. The
 * PWA must still build and still be usable, so the alias degrades in three
 * steps and the UI is told which step it got via `__CORE_MODE__`:
 *
 *   'src'   core/src/index.ts       — preferred: always fresh, no build order
 *   'dist'  core/dist/index.js      — tsc output, used when src is absent
 *   'stub'  web/src/core-stub.ts    — verbatim passthrough, app runs degraded
 *
 * Aliasing the source rather than the package entry also means `npm run build`
 * in web/ alone does not require core/ to have been compiled first.
 */
const coreMode: 'src' | 'dist' | 'stub' = existsSync(resolve(coreDir, 'src/index.ts'))
  ? 'src'
  : existsSync(resolve(coreDir, 'dist/index.js'))
    ? 'dist'
    : 'stub';

const coreEntry =
  coreMode === 'src'
    ? resolve(coreDir, 'src/index.ts')
    : coreMode === 'dist'
      ? resolve(coreDir, 'dist/index.js')
      : resolve(webDir, 'src/core-stub.ts');

// types.ts predates the rest of the engine, so `@odia/core/types` resolves even
// in 'stub' mode. Its imports are type-only and erased, but keeping the alias
// means the stub path never depends on core/dist having been compiled.
const typesEntry =
  coreMode === 'dist' ? resolve(coreDir, 'dist/types.js') : resolve(coreDir, 'src/types.ts');

/**
 * Emit a service worker that precaches everything the build produced.
 *
 * Deliberately hand-rolled instead of pulling in vite-plugin-pwa: the app shell
 * is a handful of files, the precache list is just "whatever landed in dist",
 * and one fewer dependency is one fewer thing to maintain.
 */
function serviceWorkerPlugin(): Plugin {
  let outDir = resolve(webDir, 'dist');
  let publicDir = resolve(webDir, 'public');

  return {
    name: 'odia-service-worker',
    apply: 'build',
    configResolved(config) {
      outDir = resolve(config.root, config.build.outDir);
      publicDir = config.publicDir;
    },
    // writeBundle, not closeBundle: under Vite 7 closeBundle can run before the
    // output directory exists. The precache list is the emitted bundle plus
    // whatever public/ contributes, taken from the source tree so it does not
    // depend on when Vite copies it.
    writeBundle(_options, bundle) {
      const files = [
        ...Object.keys(bundle),
        ...walk(publicDir).map((absolute) => relative(publicDir, absolute)),
      ]
        .map((path) => path.split('\\').join('/'))
        .filter((path) => path !== 'sw.js' && !path.endsWith('.map'))
        .filter((path, index, all) => all.indexOf(path) === index)
        .sort();

      // The cache name changes whenever the file list changes, which is what
      // evicts the previous version on activate.
      const revision = hash(files.join('|'));
      const precache = JSON.stringify(['./', ...files.map((f) => './' + f)], null, 2);

      mkdirSync(outDir, { recursive: true });
      writeFileSync(join(outDir, 'sw.js'), serviceWorkerSource(revision, precache), 'utf8');
      this.info(`service worker: ${files.length} precached files, revision ${revision}`);
    },
  };
}

function walk(dir: string): string[] {
  if (!existsSync(dir)) return [];
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

/** Small non-cryptographic hash; it only has to change when the file list does. */
function hash(s: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i += 1) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(36);
}

function serviceWorkerSource(revision: string, precache: string): string {
  return `/* Generated by web/vite.config.ts. Do not edit. */
'use strict';

// Cache Storage is shared by every app on the origin. This worker owns only the
// caches that start with PREFIX: it never deletes or reads another app's cache.
var PREFIX = 'odia-pwa-';
var CACHE = PREFIX + '${revision}';
var PRECACHE = ${precache};
var INDEX = new URL('./index.html', self.location).href;

function absolute(path) {
  return new URL(path, self.location).href;
}

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(CACHE).then(function (cache) {
      // Individually, not addAll: one 404 must not void the whole precache.
      return Promise.all(
        PRECACHE.map(function (path) {
          return cache.add(new Request(absolute(path), { cache: 'reload' })).catch(function () {});
        })
      );
    }).then(function () {
      return self.skipWaiting();
    })
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(
        keys.map(function (key) {
          return key === CACHE || key.indexOf(PREFIX) !== 0 ? undefined : caches.delete(key);
        })
      );
    }).then(function () {
      return self.clients.claim();
    })
  );
});

self.addEventListener('fetch', function (event) {
  var request = event.request;
  if (request.method !== 'GET') return;
  if (new URL(request.url).origin !== self.location.origin) return;

  // Navigations always resolve to the cached shell, so a cold offline launch
  // from the Home Screen works.
  if (request.mode === 'navigate') {
    event.respondWith(
      caches.open(CACHE).then(function (cache) {
        return cache.match(INDEX);
      }).then(function (hit) {
        return hit || fetch(request);
      })
    );
    return;
  }

  event.respondWith(
    caches.open(CACHE).then(function (cache) {
      return cache.match(request, { ignoreSearch: true });
    }).then(function (hit) {
      if (hit) return hit;
      return fetch(request).then(function (response) {
        if (response && response.ok && response.type === 'basic') {
          var copy = response.clone();
          caches.open(CACHE).then(function (cache) {
            cache.put(request, copy);
          });
        }
        return response;
      });
    })
  );
});
`;
}

/*
 * SINGLE_FILE=1 produces a build that can be collapsed into one .html.
 *
 * The normal build code-splits the lexicon into its own chunk and loads it with
 * a dynamic import, which is right for a served PWA and wrong for a file you
 * AirDrop: a file:// page cannot fetch a sibling chunk, so the app would come up
 * with no vocabulary and silently fall back to rule-only output.
 *
 * Inlining dynamic imports puts the lexicon in the same chunk, after which
 * web/scripts/make-single-file.mjs folds everything into docs/odia-app.html.
 * The service worker is skipped: it caches network requests, and there are none.
 */
const singleFile = process.env.SINGLE_FILE === '1';

/*
 * LEGACY=1 targets older Safari — specifically macOS Big Sur, where the normal
 * build dies with "Object.hasOwn is not a function". That method is ES2022 and
 * needs Safari 15.4; Big Sur ships 14.x for most people, and it arrives via the
 * smol-toml dependency rather than our own source.
 *
 * Two changes are needed, and only together:
 *   - a lower `target`, which downlevels modern SYNTAX
 *   - the polyfill banner, because esbuild never shims BUILT-INS at any target
 */
const legacy = process.env.LEGACY === '1';
const legacyPolyfills = legacy
  ? readFileSync(resolve(webDir, 'legacy-polyfills.js'), 'utf8')
  : '';

/*
 * Polyfills, prepended to the bundle.
 *
 * A build `target` only rewrites SYNTAX. It does not add missing built-in
 * METHODS, and esbuild injects no polyfills — so a modern method from a
 * dependency sails straight through and dies at runtime on an older browser.
 *
 * That is exactly what happened: smol-toml (the TOML parser) calls
 * `Object.hasOwn`, which Safari only shipped in 15.4. On an older Mac the app
 * died with "Object.hasOwn is not a function" before the engine could start.
 * Testing against current WebKit could never have caught it.
 *
 * These are prepended as a banner rather than imported, so they are guaranteed
 * to run before any dependency code regardless of module order.
 */
const POLYFILLS = `
if (!Object.hasOwn) {
  Object.defineProperty(Object, 'hasOwn', {
    value: function (o, k) { return Object.prototype.hasOwnProperty.call(Object(o), k); },
    configurable: true, writable: true,
  });
}
if (!String.prototype.replaceAll) {
  Object.defineProperty(String.prototype, 'replaceAll', {
    value: function (search, replace) {
      if (Object.prototype.toString.call(search) === '[object RegExp]') {
        if (!search.global) throw new TypeError('replaceAll must be called with a global RegExp');
        return this.replace(search, replace);
      }
      return this.split(search).join(replace);
    },
    configurable: true, writable: true,
  });
}
`.trim();

export default defineConfig({
  // Relative base, so the built app works from a subpath as well as from root.
  base: './',
  resolve: {
    alias: [
      { find: /^@odia\/core\/types$/, replacement: typesEntry },
      { find: /^@odia\/core$/, replacement: coreEntry },
    ],
  },
  define: {
    __CORE_MODE__: JSON.stringify(coreMode),
  },
  build: {
    outDir: legacy ? 'dist-legacy' : singleFile ? 'dist-single' : 'dist',
    // Lowered from safari15 after a real failure on an older Mac. This handles
    // SYNTAX only (private class fields were the binding constraint at 14.1);
    // missing METHODS are covered by POLYFILLS above.
    target: ['es2019', 'safari13'],
    cssTarget: 'safari13',
    assetsInlineLimit: 0,
    reportCompressedSize: true,
    // The pruned lexicon is a multi-MB data chunk by design. Warning about it on
    // every build would just train us to ignore the warning.
    chunkSizeWarningLimit: singleFile ? 100_000 : 2000,
    rollupOptions: {
      output: {
        banner: POLYFILLS,
        ...(singleFile ? { inlineDynamicImports: true } : {}),
      },
    },
  },
  server: {
    // The engine, rules and data live outside web/, so the dev server needs
    // permission to read them.
    fs: { allow: [repoRoot] },
  },
  plugins: singleFile || legacy ? [] : [serviceWorkerPlugin()],
});
